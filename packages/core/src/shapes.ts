export interface ShapeOptions {
  /** 色卡下标 */
  color: number;
  paletteId?: string;
}

/** 文字区域（支持多行；scale=像素放大倍数） */
export function makeTextRegion(
  text: string,
  options: ShapeOptions & { scale?: number; spacing?: number },
): Pattern {
  const scale = Math.max(1, Math.round(options.scale ?? 1));
  const spacing = Math.max(0, Math.round(options.spacing ?? 1));
  const lines = text.split('\n');
  const lineH = (GLYPH_H + 1) * scale;
  const maxLen = Math.max(1, ...lines.map((l) => l.length));
  const w = Math.max(1, (maxLen * (GLYPH_W + spacing) - spacing) * scale);
  const h = Math.max(1, lines.length * lineH - scale);
  const region = createPattern(w, h, options.paletteId ?? 'mard-221');
  lines.forEach((line, li) => {
    const baseY = li * lineH;
    [...line.toUpperCase()].forEach((ch, ci) => {
      const glyph = FONT[ch] ?? FONT[' '];
      const baseX = ci * (GLYPH_W + spacing) * scale;
      for (let gy = 0; gy < GLYPH_H; gy++) {
        const row = glyph[gy];
        for (let gx = 0; gx < GLYPH_W; gx++) {
          if ((row >> (GLYPH_W - 1 - gx)) & 1) {
            for (let sy = 0; sy < scale; sy++) {
              for (let sx = 0; sx < scale; sx++) {
                const px = baseX + gx * scale + sx;
                const py = baseY + gy * scale + sy;
                if (px < w && py < h) region.grid[py * w + px] = options.color;
              }
            }
          }
        }
      }
    });
  });
  return region;
}

/** 矩形区域（filled=实心；否则描边，thickness=边框格数） */
export function makeRectRegion(
  width: number,
  height: number,
  options: ShapeOptions & { filled?: boolean; thickness?: number },
): Pattern {
  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new Error('形状尺寸必须是正整数');
  }
  const region = createPattern(width, height, options.paletteId ?? 'mard-221');
  const t = Math.max(1, Math.round(options.thickness ?? 1));
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const edge = x < t || y < t || x >= width - t || y >= height - t;
      if (options.filled !== false || edge) region.grid[y * width + x] = options.color;
    }
  }
  return region;
}

/** 椭圆区域（filled=实心；否则描边） */
export function makeEllipseRegion(
  width: number,
  height: number,
  options: ShapeOptions & { filled?: boolean; thickness?: number },
): Pattern {
  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new Error('形状尺寸必须是正整数');
  }
  const region = createPattern(width, height, options.paletteId ?? 'mard-221');
  const t = Math.max(1, Math.round(options.thickness ?? 1));
  const rx = width / 2;
  const ry = height / 2;
  const inner = 1 - (2 * t) / Math.min(width, height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const nx = (x + 0.5 - rx) / rx;
      const ny = (y + 0.5 - ry) / ry;
      const d = nx * nx + ny * ny;
      const inOuter = d <= 1.05;
      const inInner = d <= inner * inner;
      if (inOuter && (options.filled !== false || !inInner)) {
        region.grid[y * width + x] = options.color;
      }
    }
  }
  return region;
}
